create extension if not exists postgis;

alter table public.drivers add column if not exists location geography(point, 4326);
update public.drivers
set location = st_setsrid(st_makepoint(longitude, latitude), 4326)::geography
where location is null and latitude is not null and longitude is not null;
create index if not exists ix_drivers_location_gist on public.drivers using gist(location);

alter table public.rides add column if not exists discount_paise integer not null default 0;
alter table public.rides add column if not exists promo_code varchar(40);

create table if not exists public.promo_codes (
  code varchar(40) primary key,
  percent_off integer not null check (percent_off between 1 and 100),
  max_discount_paise integer not null check (max_discount_paise >= 0),
  max_uses integer not null check (max_uses > 0),
  uses integer not null default 0 check (uses >= 0),
  active boolean not null default true
);
insert into public.promo_codes (code, percent_off, max_discount_paise, max_uses, uses, active)
values ('WELCOME10', 10, 5000, 100000, 0, true)
on conflict (code) do nothing;

create table if not exists public.wallets (
  user_id integer primary key references public.users(id) on delete cascade,
  balance_paise bigint not null default 0 check (balance_paise >= 0),
  updated_at timestamptz not null default now()
);
create table if not exists public.wallet_transactions (
  id bigint generated by default as identity primary key,
  user_id integer not null references public.users(id) on delete cascade,
  ride_id integer references public.rides(id),
  amount_paise bigint not null,
  kind varchar(24) not null check (kind in ('topup', 'ride_payment')),
  reference varchar(255) unique,
  created_at timestamptz not null default now()
);
create index if not exists ix_wallet_transactions_user_id on public.wallet_transactions(user_id);

create table if not exists public.ride_receipts (
  ride_id integer primary key references public.rides(id) on delete cascade,
  pdf bytea not null,
  created_at timestamptz not null default now()
);

alter table public.promo_codes enable row level security;
alter table public.wallets enable row level security;
alter table public.wallet_transactions enable row level security;
alter table public.ride_receipts enable row level security;
