create table if not exists public.users (
  id integer generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(255) not null,
  password_hash varchar(255) not null,
  role varchar(20) not null default 'rider' check (role in ('rider', 'driver')),
  created_at timestamptz not null default now()
);

create table if not exists public.drivers (
  id integer generated by default as identity primary key,
  user_id integer unique references public.users(id),
  name varchar(100) not null,
  car varchar(100) not null,
  plate varchar(20) not null,
  ride_type varchar(20) not null check (ride_type in ('mini', 'comfort', 'xl')),
  rating double precision not null default 4.9,
  available boolean not null default true
);

create table if not exists public.rides (
  id integer generated by default as identity primary key,
  rider_id integer not null references public.users(id),
  driver_id integer references public.drivers(id),
  pickup varchar(300) not null,
  destination varchar(300) not null,
  ride_type varchar(20) not null check (ride_type in ('mini', 'comfort', 'xl')),
  status varchar(30) not null default 'requested',
  distance_km double precision not null,
  duration_min integer not null,
  fare_paise integer not null,
  payment_status varchar(30) not null default 'unpaid',
  stripe_payment_intent_id varchar(255),
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id integer generated by default as identity primary key,
  ride_id integer not null unique references public.rides(id),
  rider_id integer not null references public.users(id),
  rating integer not null check (rating between 1 and 5),
  comment text not null default ''
);

create unique index if not exists ix_users_email on public.users(email);
create index if not exists ix_rides_rider_id on public.rides(rider_id);
create index if not exists ix_rides_status on public.rides(status);
create index if not exists ix_rides_created_at on public.rides(created_at);

alter table public.users enable row level security;
alter table public.drivers enable row level security;
alter table public.rides enable row level security;
alter table public.reviews enable row level security;
